// ⭐ Fonction de détection : ville OU quartier
export function detectLocation(input: string): {
  city: string | null;
  quartier: string | null;
  type: 'city' | 'quartier' | 'unknown';
} {
  const lower = input.toLowerCase();

  // 1. Chercher un quartier d'abord (plus spécifique)
  const quartierKeys = Object.keys(QUARTIER_MAP).sort(
    (a, b) => b.length - a.length
  );
  for (const key of quartierKeys) {
    if (new RegExp(`\\b${key}\\b`, 'i').test(lower)) {
      return {
        city: QUARTIER_MAP[key],
        quartier: key,
        type: 'quartier',
      };
    }
  }

  // 2. Chercher une ville
  const cityKeys = Object.keys(CITY_MAP).sort((a, b) => b.length - a.length);
  for (const key of cityKeys) {
    if (new RegExp(`\\b${key}\\b`, 'i').test(lower)) {
      return {
        city: CITY_MAP[key],
        quartier: null,
        type: 'city',
      };
    }
  }

  return { city: null, quartier: null, type: 'unknown' };
}

// Compatibilité : detectCity appelle detectLocation
export function detectCity(input: string): string | undefined {
  const result = detectLocation(input);
  return result.city || undefined;
}

