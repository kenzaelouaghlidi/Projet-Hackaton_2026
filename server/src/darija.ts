// ═══════════════════════════════════════════════════════════════
// TRADUCTION
// ═══════════════════════════════════════════════════════════════
export function translateDarija(input: string): string {
  let translated = input.toLowerCase();

  const sortedWords = Object.entries(DARIJA_TO_FRENCH).sort(
    (a, b) => b[0].length - a[0].length
  );

  for (const [darija, french] of sortedWords) {
    const regex = new RegExp(`(^|\\s|[.,!?])${darija}(\\s|$|[.,!?])`, 'gi');
    translated = translated.replace(regex, `$1${french}$2`);
  }

  return translated;
}

